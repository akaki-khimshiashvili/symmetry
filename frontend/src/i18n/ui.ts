/** Route helpers: Georgian lives at the root, English under /en/. */
export function path(lang: Lang, p = '/') {
  const clean = p.startsWith('/') ? p : `/${p}`;
  return lang === 'ka' ? clean : `/en${clean === '/' ? '/' : clean}`;
}

export function altPath(currentPath: string, target: Lang) {
  const stripped = currentPath.replace(/^\/en(?=\/|$)/, '') || '/';
  return path(target, stripped);
}

